using ModelSwitch.SharedKernel;

namespace ModelSwitch.Usage.Contracts;

/// <summary>Who caused an Inference Request (Request Origin). Evaluation traffic carries the run, not an API Key.</summary>
public enum RequestOrigin
{
    Api,
    Evaluation,
}

/// <summary>The terminal state of an Inference Request. <c>running</c> and <c>abandoned</c> are never set by a caller.</summary>
public enum RequestOutcome
{
    Succeeded,
    Failed,
    Cancelled,
}

/// <summary>Why an Attempt was made.</summary>
public enum AttemptKind
{
    Primary,
    Retry,
    Fallback,
}

/// <summary>How an Attempt ended (routing-and-resilience.md section 3).</summary>
public enum AttemptStatus
{
    Succeeded,
    Failed,
    Cancelled,
    Ambiguous,
    SkippedCircuitOpen,
}

/// <summary>Failure class of an Attempt that did not succeed.</summary>
public enum AttemptErrorClass
{
    Transient,
    Permanent,
    Ambiguous,
}

/// <summary>Where an Attempt's token counts came from (usage-and-budgets.md section 2). Worst-first order: reported &lt; estimated &lt; unavailable.</summary>
public enum UsageSource
{
    Reported,
    Estimated,
    Unavailable,
}

/// <summary>An Inference Request that has been accepted for execution. Contains metadata only, never content (ADR-0010).</summary>
/// <param name="RequestId">The Inference Request ID (UUIDv7), also returned in <c>X-Request-Id</c>.</param>
/// <param name="TenantId">The Tenant that pays for the request.</param>
/// <param name="Origin">Api, or Evaluation for traffic generated by an Evaluation Run.</param>
/// <param name="ApiKeyId">Set exactly when <paramref name="Origin"/> is Api.</param>
/// <param name="EvaluationRunId">Set exactly when <paramref name="Origin"/> is Evaluation.</param>
/// <param name="ClientRequestId"><c>X-Client-Request-Id</c>, if the client sent one.</param>
/// <param name="RequestedAlias">The Model Alias the client asked for.</param>
/// <param name="TaskType">The Task Type, if any.</param>
/// <param name="Streaming">Whether the client asked for a stream.</param>
/// <param name="InputBytes">Size of the request body in bytes (a size, not content).</param>
/// <param name="TraceId">W3C trace id of the request, or empty when there is no trace.</param>
/// <param name="Reservation">The Budget hold to place with the request; null places none.</param>
public sealed record OpenInferenceRequest(
    Guid RequestId,
    Guid TenantId,
    RequestOrigin Origin,
    Guid? ApiKeyId,
    Guid? EvaluationRunId,
    string? ClientRequestId,
    string RequestedAlias,
    string? TaskType,
    bool Streaming,
    int InputBytes,
    string TraceId,
    ReservationRequest? Reservation = null);

/// <summary>A worst-case hold against the Tenant's Budget (usage-and-budgets.md section 3).</summary>
/// <param name="Amount">The worst-case cost of the most expensive Candidate times <c>min(maxAttempts, 2)</c>.</param>
/// <param name="ExpiresAt">When the sweeper may treat the request as abandoned: the Deadline plus a grace period.</param>
public sealed record ReservationRequest(Money Amount, DateTimeOffset ExpiresAt);

/// <summary>The Price an Attempt is costed with: the immutable Price row in force at Attempt start, and its rates.</summary>
/// <param name="ModelPriceId">The <c>model_price</c> row, recorded on the Usage Record so history never changes when Prices do.</param>
/// <param name="Rates">Its per-million-token rates.</param>
public sealed record AttemptPricing(Guid? ModelPriceId, PriceRates Rates);

/// <summary>What <see cref="IUsageLedger.OpenAsync"/> hands back; pass <see cref="StartedAt"/> to <see cref="IUsageLedger.SettleAsync"/>.</summary>
/// <param name="RequestId">The opened request.</param>
/// <param name="StartedAt">When the request row was written (the ledger's clock). Also the partition key.</param>
public sealed record OpenedRequest(Guid RequestId, DateTimeOffset StartedAt);

/// <summary>One Attempt, as the executor observed it. <see cref="AttemptRecord.EstimatedCost"/> is null until Usage Records exist (Phase 3).</summary>
/// <param name="AttemptNumber">1-based, unique within the request.</param>
/// <param name="ProviderId">The Provider that was called.</param>
/// <param name="ProviderModelId">The Provider Model that was called.</param>
/// <param name="Kind">Primary, Retry or Fallback.</param>
/// <param name="Status">How the Attempt ended.</param>
/// <param name="ErrorClass">Null when the Attempt succeeded.</param>
/// <param name="ErrorCode">The gateway error code the failure maps to, from the closed set; null on success.</param>
/// <param name="HttpStatus">The Provider's HTTP status, if it answered.</param>
/// <param name="ProviderErrorType">A sanitized failure code, at most 64 characters. Never Provider free text.</param>
/// <param name="StartedAt">When the Attempt began.</param>
/// <param name="CompletedAt">When it ended.</param>
/// <param name="TtftMs">Time to first token; streaming Attempts only.</param>
/// <param name="InputTokens">Null when unknown.</param>
/// <param name="OutputTokens">Null when unknown.</param>
/// <param name="UsageSource">Provenance of the token counts.</param>
/// <param name="EstimatedCost">Filled by the ledger at settlement from <paramref name="Pricing"/>; callers leave it null.</param>
/// <param name="CachedInputTokens">Provider-reported cached subset of <paramref name="InputTokens"/>; null when not reported.</param>
/// <param name="EstimateMethod">How an estimated token count was obtained (<c>tokenizer:o200k_base</c>, <c>bytes_div_3</c>).</param>
/// <param name="Pricing">The Price in force when the Attempt started; null costs the Attempt at zero with no Price recorded.</param>
public sealed record AttemptRecord(
    int AttemptNumber,
    Guid ProviderId,
    Guid ProviderModelId,
    AttemptKind Kind,
    AttemptStatus Status,
    AttemptErrorClass? ErrorClass,
    string? ErrorCode,
    int? HttpStatus,
    string? ProviderErrorType,
    DateTimeOffset StartedAt,
    DateTimeOffset CompletedAt,
    int? TtftMs,
    int? InputTokens,
    int? OutputTokens,
    UsageSource UsageSource,
    Money? EstimatedCost = null,
    int? CachedInputTokens = null,
    string? EstimateMethod = null,
    AttemptPricing? Pricing = null);

/// <summary>Everything known when an Inference Request ends.</summary>
/// <param name="RequestId">The request opened earlier.</param>
/// <param name="StartedAt">From <see cref="OpenedRequest"/>.</param>
/// <param name="Outcome">Succeeded, Failed or Cancelled.</param>
/// <param name="ErrorCode">The gateway error code the client saw; null on success.</param>
/// <param name="PolicyId">The Routing Policy, once resolved.</param>
/// <param name="PolicyVersion">The Policy Version, once resolved.</param>
/// <param name="RoutingDecisionJson">The Routing Decision as JSON (candidates, exclusions, rule); metadata only.</param>
/// <param name="TtftMs">Time to first token of the winning Attempt; streaming only.</param>
/// <param name="Attempts">Every Attempt made, in order. May be empty (the request failed before any Attempt).</param>
/// <param name="MaxOutputTokens">The output ceiling the request ran with; an ambiguous Attempt's worst-case cost uses it. Null uses the default.</param>
public sealed record SettleInferenceRequest(
    Guid RequestId,
    DateTimeOffset StartedAt,
    RequestOutcome Outcome,
    string? ErrorCode,
    Guid? PolicyId,
    int? PolicyVersion,
    string? RoutingDecisionJson,
    int? TtftMs,
    IReadOnlyList<AttemptRecord> Attempts,
    int? MaxOutputTokens = null);

/// <summary>
/// The durable record of what the gateway did (usage-and-budgets.md, architecture.md section 5). <see cref="OpenAsync"/> is
/// step 8 of the request lifecycle and <see cref="SettleAsync"/> is step 11; each is one database transaction. Phase 3
/// adds the Budget Reservation to the open transaction and the Usage Records and budget settlement to the settle one,
/// behind these same two methods.
/// </summary>
public interface IUsageLedger
{
    /// <summary>
    /// Step 8, one transaction: places the Reservation (when given) and writes the Inference Request with <c>status = running</c>.
    /// Fails with <c>budget_exceeded</c> when reserved + spent + hold would pass the Tenant's limit; the request is then recorded
    /// as <c>failed</c> with no Reservation. Infrastructure faults throw.
    /// </summary>
    Task<Result<OpenedRequest>> OpenAsync(OpenInferenceRequest request, CancellationToken cancellationToken);

    /// <summary>
    /// Completes the request and records its Attempts. Idempotent: settling a request that is no longer <c>running</c> does
    /// nothing, so a retry after an ambiguous database failure cannot double-record. Request totals, <c>attempt_count</c>,
    /// <c>had_fallback</c>, the selected Provider Model and the worst-of <c>usage_status</c> are derived from
    /// <see cref="SettleInferenceRequest.Attempts"/>. Callers pass a fresh, short-timeout token when the client has gone away.
    /// </summary>
    Task SettleAsync(SettleInferenceRequest settlement, CancellationToken cancellationToken);

    /// <summary>
    /// Raises the request's held amount by <paramref name="additional"/> with the same conditional update as the reservation, before an
    /// Attempt whose worst case would pass the hold. Fails with <c>budget_exceeded</c> when the Budget cannot take it.
    /// </summary>
    Task<Result> TopUpAsync(Guid requestId, Money additional, CancellationToken cancellationToken);
}
